"""Read-only CI diagnostic for the disposable R207 WGL ArrayList framebuffer.

The PPM is generated by the isolated GL test, not a Minecraft capture.
OpenGL sample coordinates are bottom-left origin; P6 rows are top-down.
Never adjusts a test's pass/fail decision.
"""
from __future__ import annotations

import argparse
from pathlib import Path


def inspect_ppm(path: Path) -> tuple[int, int, bytes]:
    if not path.is_file() or path.stat().st_size > 2_000_000:
        raise ValueError("PPM missing or exceeds the 2 MB fixture limit")
    raw = path.read_bytes()
    header = raw.split(b"\n", 3)
    if len(header) != 4 or header[0] != b"P6" or header[2] != b"255":
        raise ValueError("expected binary P6 RGB with max value 255")
    dimensions = header[1].split(b" ")
    if len(dimensions) != 2 or any(not x.isdigit() for x in dimensions):
        raise ValueError("invalid PPM dimensions")
    width, height = (int(x) for x in dimensions)
    if not (1 <= width <= 1500 and 1 <= height <= 8192):
        raise ValueError("PPM dimensions outside fixture bounds")
    pixels = header[3]
    if len(pixels) != width * height * 3:
        raise ValueError("PPM RGB payload length mismatch")
    return width, height, pixels


def sample_gl(width: int, height: int, pixels: bytes, x: int, y: int) -> tuple[int, int, int]:
    if not (0 <= x < width and 0 <= y < height):
        raise ValueError("sample outside viewport")
    offset = ((height - 1 - y) * width + x) * 3
    return tuple(pixels[offset:offset + 3])


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("ppm", type=Path, help="isolated fixture P6 frame")
    args = parser.parse_args()
    width, height, pixels = inspect_ppm(args.ppm)
    print(f"R218_WGL_CI_FRAMEBUFFER={width}x{height}")
    for x, y in ((666, 612), (666, 590), (662, 612), (4, 628)):
        if x >= width or y >= height:
            continue
        rgb = sample_gl(width, height, pixels, x, y)
        print(f"R218_WGL_PIXEL_GL({x},{y})={rgb[0]:02X}{rgb[1]:02X}{rgb[2]:02X}")
    print("R218_EXPECTED_ARRAYLIST_ACCENT=F35D12")
    return 0


if __name__ == "__main__":
    try:
        raise SystemExit(main())
    except (OSError, ValueError) as exc:
        raise SystemExit(f"R218_WGL_DIAGNOSTIC_UNAVAILABLE: {exc}")
